test("processRecurringExpense skips duplicates and saves only new due occurrences", () => {
  const saved = []
  const duplicateKeys = new Set(["rule-1::2026-01-01 00:00:00.000Z"])
  let nextExpenseId = 1
  const txApp = {
    findCollectionByNameOrId(name) {
      return { name }
    },
    findRecordsByFilter(collection, filter, sort, limit, offset, params) {
      const key = params.recurringExpense + "::" + params.scheduledFor
      return duplicateKeys.has(key) ? [{}] : []
    },
    save(record) {
      if (record.collection && record.collection.name === "expenses" && !record.id) {
        record.id = "expense-" + nextExpenseId
        nextExpenseId += 1
      }
      saved.push(record)
    },
  }

  const rule = createRecurringRule({
    id: "rule-1",
    nextRunAt: "2026-01-01 00:00:00.000Z",
    intervalUnit: "month",
    intervalCount: 1,
    household: "home-1",
    description: "Rent",
    amount: 650,
    paidBy: "user-1",
    splitBetween: ["user-1", "user-2"],
    splitMode: "equal",
    splitShares: "",
    notes: "",
    createdBy: "user-1",
  })

  const result = processRecurringExpense(txApp, rule, "2026-03-15 00:00:00.000Z")

  assert.deepEqual(result.generated, [
    "2026-02-01 00:00:00.000Z",
    "2026-03-01 00:00:00.000Z",
  ])
  assert.equal(result.skippedDuplicates, 1)
  assert.equal(saved.length, 3)
  assert.equal(saved[0].values.recurringExpense, "rule-1")
  assert.equal(saved[0].values.scheduledFor, "2026-02-01 00:00:00.000Z")
  assert.equal(saved[1].values.scheduledFor, "2026-03-01 00:00:00.000Z")
  assert.equal(saved[2], rule)
  assert.equal(rule.values.lastGeneratedExpense, "expense-2")
  assert.equal(rule.values.lastRunAt, "2026-03-01 00:00:00.000Z")
  assert.equal(rule.values.nextRunAt, "2026-04-01 00:00:00.000Z")
  assert.equal(rule.values.lastError, "")
})

test("processRecurringExpense clears stale errors when all due runs are duplicate matches", () => {
  const saved = []
  const duplicateKeys = new Set([
    "rule-1::2026-01-01 00:00:00.000Z",
    "rule-1::2026-02-01 00:00:00.000Z",
  ])
  const txApp = {
    findCollectionByNameOrId(name) {
      return { name }
    },
    findRecordsByFilter(collection, filter, sort, limit, offset, params) {
      const key = params.recurringExpense + "::" + params.scheduledFor
      return duplicateKeys.has(key) ? [{}] : []
    },
    save(record) {
      saved.push(record)
    },
  }

  const rule = createRecurringRule({
    id: "rule-1",
    nextRunAt: "2026-01-01 00:00:00.000Z",
    intervalUnit: "month",
    intervalCount: 1,
    household: "home-1",
    description: "Rent",
    amount: 650,
    paidBy: "user-1",
    splitBetween: ["user-1", "user-2"],
    splitMode: "equal",
    splitShares: "",
    notes: "",
    createdBy: "user-1",
    lastError: "previous failure",
  })

  const result = processRecurringExpense(txApp, rule, "2026-02-20 00:00:00.000Z")

  assert.deepEqual(result.generated, [])
  assert.equal(result.skippedDuplicates, 2)
  assert.equal(saved.length, 1)
  assert.equal(saved[0], rule)
  assert.equal(rule.values.lastError, "")
  assert.equal(rule.values.lastRunAt, "2026-02-01 00:00:00.000Z")
  assert.equal(rule.values.nextRunAt, "2026-03-01 00:00:00.000Z")
})
